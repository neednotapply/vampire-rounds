"""Vampire Rounds design sheets: preflight and code generation.

usage: python -I tools/sheets.py preflight [--code] [--package <zip>]
       python -I tools/sheets.py gen
The sheets in sheets/*.json are the source of truth. Preflight lists every unfilled cell, every reference between
sheets that does not resolve, every game target that does not exist in the decompiled games and (with --code) every
symbol a row names that is missing from src/. Generated code goes to src/Shared/Generated and src/VsMod/Generated.
"""
import json, os, re, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEETS = os.path.join(ROOT, "sheets")
SRC = os.path.join(ROOT, "src")
GEN_SHARED = os.path.join(SRC, "Shared", "Generated")
GEN_VS = os.path.join(SRC, "VsMod", "Generated")
HOME = os.path.expanduser("~")
# Decompiled games on the developer's machine (never in the repository): VS signatures from Cpp2IL + ILSpy, ROUNDS from ILSpy.
DECOMP = {
    "vs": os.environ.get("VSR_VS_DECOMP", os.path.join(HOME, "vsr-work", "vs-decomp", "runtime")),
    "rounds": os.environ.get("VSR_ROUNDS_DECOMP", os.path.join(HOME, "cuprounds-decomp", "rounds")),
}
HDR = "// <auto-generated> from sheets/*.json by tools/sheets.py gen. Edit the sheet, not this file.\n"


def load():
    out = {}
    for f in sorted(os.listdir(SHEETS)):
        if f.endswith(".json"):
            with open(os.path.join(SHEETS, f), encoding="utf-8") as fh:
                d = json.load(fh)
            out[d["sheet"]] = d
    return out


def ids(s, name):
    return {r["id"] for r in s[name]["rows"]}


def split(v):
    return [x.strip() for x in str(v).split(",") if x.strip() and x.strip() != "none"]


_src_cache = None


def src_files():
    global _src_cache
    if _src_cache is None:
        _src_cache = {}
        for d, _, fs in os.walk(SRC):
            if os.sep + "obj" in d or os.sep + "bin" in d:
                continue
            for f in fs:
                if f.endswith(".cs"):
                    p = os.path.join(d, f)
                    with open(p, encoding="utf-8") as fh:
                        _src_cache[p] = fh.read()
    return _src_cache


def symbol_exists(sym):
    cls, meth = sym.split(".", 1)
    for p, text in src_files().items():
        for m in re.finditer(r"\b(class|struct)\s+%s\b" % re.escape(cls), text):
            if re.search(r"\b%s\s*[\(<]" % re.escape(meth), text[m.start():]):
                return True
    return False


_decomp_index = {}


def decomp_file(game, cls):
    """The decompiled file of a class (VS files sit in namespace folders, ROUNDS's in one folder)."""
    root = DECOMP[game]
    if game not in _decomp_index:
        idx = {}
        for d, _, fs in os.walk(root):
            for f in fs:
                if f.endswith(".cs"):
                    idx.setdefault(f[:-3], []).append(os.path.join(d, f))
        _decomp_index[game] = idx
    return _decomp_index[game].get(cls, [])


def game_target_exists(game, target):
    parts = target.split(".")  # Class.Method, or Class.Nested.Method (the nested class lives in the outer class's file)
    cls, meth = parts[0], parts[-1]
    for p in decomp_file(game, cls):
        with open(p, encoding="utf-8", errors="replace") as fh:
            if re.search(r"\b%s\s*\(" % re.escape(meth), fh.read()):
                return True
    return False


# One enum member line in a decompiled enum: "\tFOREST = 0," (the value and the comma are optional).
ENUM_LINE = r"^[ \t]*%s\b[ \t]*(=[^,\r\n]*)?,?[ \t]*\r?$"


def enum_has(game, enum, member):
    for p in decomp_file(game, enum):
        with open(p, encoding="utf-8", errors="replace") as fh:
            if re.search(ENUM_LINE % re.escape(member), fh.read(), re.M):
                return True
    return False


BLOCK_LIMIT = {"control": 65536, "result": 65536, "seat": 64, "seat2": 32, "rseat": 64, "event": 32, "pick": 96, "target": 24, "hit": 32, "fx": 32, "status": 32}


def preflight(check_code, package):
    s = load()
    problems = []
    # 1. every cell filled, no unknown columns, no duplicate ids
    for name, sh in s.items():
        cols = list(sh["columns"].keys())
        for i, row in enumerate(sh["rows"]):
            for c in cols:
                v = row.get(c)
                if v is None or (isinstance(v, str) and v.strip() == ""):
                    problems.append("%s[%s].%s is empty" % (name, row.get("id", i), c))
            for c in row:
                if c not in cols:
                    problems.append("%s[%s] has unknown column %s" % (name, row.get("id", i), c))
        seen = set()
        for row in sh["rows"]:
            if row.get("id") in seen:
                problems.append("%s has duplicate id %s" % (name, row["id"]))
            seen.add(row.get("id"))
    # 2. the link layout: fields of a block never overlap and fit their block
    by_block = {}
    for r in s["link"]["rows"]:
        if r["block"] == "layout":
            if r["type"] != "const":
                problems.append("link[%s]: layout rows are const" % r["id"])
            continue
        if r["type"] not in ("int", "float"):
            problems.append("link[%s]: type %s" % (r["id"], r["type"]))
        by_block.setdefault(r["block"], []).append(r)
    for b, rows in by_block.items():
        lim = BLOCK_LIMIT.get(b)
        if lim is None:
            problems.append("link: unknown block %s" % b)
            continue
        used = {}
        for r in rows:
            off = int(r["offset"])
            if off % 4 or off + 4 > lim:
                problems.append("link[%s]: offset %d outside %s (%d bytes) or unaligned" % (r["id"], off, b, lim))
            if off in used:
                problems.append("link[%s] overlaps link[%s]" % (r["id"], used[off]))
            used[off] = r["id"]
    # 3. references between sheets
    tun, link, chars, stages = ids(s, "tuning"), ids(s, "link"), ids(s, "characters"), ids(s, "stages")
    for r in s["content"]["rows"]:
        for l in split(r["link"]):
            if l not in link:
                problems.append("content[%s].link -> %s does not resolve" % (r["id"], l))
    for r in s["effects"]["rows"]:
        for t in split(r["tuning"]):
            if t not in tun:
                problems.append("effects[%s].tuning -> %s does not resolve" % (r["id"], t))
        for l in split(r["link"]):
            if l not in link:
                problems.append("effects[%s].link -> %s does not resolve" % (r["id"], l))
    for r in s["progression"]["rows"]:
        if r["picks"] not in tun:
            problems.append("progression[%s].picks -> %s does not resolve" % (r["id"], r["picks"]))
    for r in s["adventure"]["rows"]:
        for c in split(r["characters"]):
            if c not in chars:
                problems.append("adventure[%s].characters -> %s does not resolve" % (r["id"], c))
        if r["startingCharacter"] not in chars:
            problems.append("adventure[%s].startingCharacter -> %s does not resolve" % (r["id"], r["startingCharacter"]))
        for st in split(r["stages"]):
            if st not in stages:
                problems.append("adventure[%s].stages -> %s does not resolve" % (r["id"], st))
    for r in s["stages"]["rows"]:
        for col in ("vsStage", "slot"):
            if not enum_has("vs", "StageType", r[col]):
                problems.append("stages[%s].%s: VS StageType %s not found" % (r["id"], col, r[col]))
        if r["unlockedBy"] != "start" and r["unlockedBy"] not in stages:
            problems.append("stages[%s].unlockedBy -> %s does not resolve" % (r["id"], r["unlockedBy"]))
        if not enum_has("vs", "AdventureAchievementType", r["goalType"]):
            problems.append("stages[%s].goalType: VS AdventureAchievementType %s not found" % (r["id"], r["goalType"]))
    for col in ("slot", "goalType", "order"):
        vals = [r[col] for r in s["stages"]["rows"]]
        for v in set(vals):
            if vals.count(v) > 1:
                problems.append("stages: %s %s used by more than one stage" % (col, v))
    if sum(1 for r in s["stages"]["rows"] if r["unlockedBy"] == "start") != 1:
        problems.append("stages: exactly one stage opens at the start")
    for r in s["texts"]["rows"]:
        for m in re.findall(r"\{type:(\w+)\}", r["term"]):
            if m not in chars:
                problems.append("texts[%s]: {type:%s} is no characters row" % (r["id"], m))
    for r in s["characters"]["rows"]:
        if not enum_has("vs", "CharacterType", r["basePrefab"]):
            problems.append("characters[%s]: VS CharacterType %s not found" % (r["id"], r["basePrefab"]))
    for r in s["hooks"]["rows"]:
        target = r["target"]
        if "(runtime patch)" in target:
            continue
        if r["game"] not in DECOMP:
            problems.append("hooks[%s]: game %s" % (r["id"], r["game"]))
            continue
        if not game_target_exists(r["game"], target):
            problems.append("hooks[%s]: %s %s not found" % (r["id"], r["game"], target))
    # 4. code symbols
    if check_code:
        checks = []
        for sheet in ("hooks", "effects", "progression", "controls", "checks", "systems"):
            for r in s[sheet]["rows"]:
                for sym in split(r["symbol"]):
                    checks.append((sheet, r["id"], sym))
        for sheet, rid, sym in checks:
            if not symbol_exists(sym):
                problems.append("%s[%s]: %s not implemented in src/" % (sheet, rid, sym))
        for p in (os.path.join(GEN_SHARED, "Link.g.cs"), os.path.join(GEN_SHARED, "Tuning.g.cs"), os.path.join(GEN_VS, "Content.g.cs")):
            if not os.path.exists(p):
                problems.append("generated code missing (%s): run gen" % os.path.basename(p))
    # 5. package contents
    if package:
        with zipfile.ZipFile(package) as z:
            names = z.namelist()
        for r in s["components"]["rows"]:
            zp = r["zipPath"]
            if zp.endswith("/"):
                if not any(n.startswith(zp) and not n.endswith("/") for n in names):
                    problems.append("components[%s]: %s empty in package" % (r["id"], zp))
            elif zp not in names:
                problems.append("components[%s]: %s missing from package" % (r["id"], zp))
        listed = [r["zipPath"] for r in s["components"]["rows"]]
        for n in names:
            if n.endswith("/"):
                continue
            if not any(n == zp or (zp.endswith("/") and n.startswith(zp)) for zp in listed):
                problems.append("package file %s is in no components row" % n)
    total = sum(len(sh["rows"]) * len(sh["columns"]) for sh in s.values())
    print("preflight: %d sheets, %d rows, %d cells" % (len(s), sum(len(sh["rows"]) for sh in s.values()), total))
    for p in problems:
        print("  OPEN " + p)
    print("clean" if not problems else "%d open items" % len(problems))
    return 0 if not problems else 1


def cs_str(v):
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen():
    s = load()
    os.makedirs(GEN_SHARED, exist_ok=True)
    os.makedirs(GEN_VS, exist_ok=True)
    # Link.g.cs: every link row is a constant of ArenaLink
    lines = [HDR, "namespace VampireRounds", "{", "    public sealed partial class ArenaLink", "    {"]
    for r in s["link"]["rows"]:
        lines.append("        /// <summary>%s: %s</summary>" % (r["block"], r["meaning"].replace("&", "and").replace("<", "(").replace(">", ")")))
        lines.append("        public const int %s = %d;" % (r["id"], int(r["offset"])))
    lines += ["    }", "}", ""]
    write(os.path.join(GEN_SHARED, "Link.g.cs"), "\n".join(lines))
    # Tuning.g.cs
    lines = [HDR, "namespace VampireRounds", "{", "    public static class Tuning", "    {"]
    for r in s["tuning"]["rows"]:
        lines.append("        /// <summary>%s (%s): %s</summary>" % (r["id"], r["unit"], r["why"].replace("&", "and").replace("<", "(").replace(">", ")")))
        lines.append("        public const float %s = %sf;" % (r["id"], repr(float(r["value"]))))
    lines += ["    }", "}", ""]
    write(os.path.join(GEN_SHARED, "Tuning.g.cs"), "\n".join(lines))
    # Content.g.cs (VS mod): characters, the adventure, its stages, test checks, hook ids
    L = [HDR, "namespace VampireRounds.Vs", "{"]
    L += ["    public sealed class CharacterRow", "    {",
          "        public string Id, VsName, Surname, Description, Color, BasePrefab, Folder;",
          "        public int Seat, WalkFrames;", "        public float MaxHp, MoveSpeed, Growth;", "    }", ""]
    L += ["    public sealed class StageRow", "    {", "        public string Id, Slot, VsStage, Name, Description, UnlockedBy, GoalType, Goal;",
          "        public int Order, Minutes, GoalMinutes, GoalGold;", "    }", ""]
    L += ["    public sealed class AdventureRow", "    {",
          "        public string Id, Name, Description, ProgressKey, StartingCharacter;",
          "        public string[] Characters, Stages;", "        public int StartingCoins, CompletionCoins;", "    }", ""]
    L += ["    public static class Sheets", "    {"]
    L.append("        public static readonly CharacterRow[] Characters = {")
    for r in s["characters"]["rows"]:
        L.append("            new CharacterRow { Id = %s, Seat = %d, VsName = %s, Surname = %s, Description = %s, Color = %s, BasePrefab = %s, Folder = %s, WalkFrames = %d, MaxHp = %sf, MoveSpeed = %sf, Growth = %sf }," % (
            cs_str(r["id"]), int(r["seat"]), cs_str(r["vsName"]), cs_str(r["surname"]), cs_str(r["description"]), cs_str(r["color"]),
            cs_str(r["basePrefab"]), cs_str(r["folder"]), int(r["walkFrames"]), repr(float(r["maxHp"])), repr(float(r["moveSpeed"])), repr(float(r["growth"]))))
    L.append("        };")
    L.append("        public static readonly StageRow[] Stages = {")
    for r in s["stages"]["rows"]:
        L.append("            new StageRow { Id = %s, Order = %d, Slot = %s, VsStage = %s, Name = %s, Description = %s, UnlockedBy = %s, Minutes = %d, GoalMinutes = %d, GoalType = %s, Goal = %s, GoalGold = %d }," % (
            cs_str(r["id"]), int(r["order"]), cs_str(r["slot"]), cs_str(r["vsStage"]), cs_str(r["name"]), cs_str(r["description"]), cs_str(r["unlockedBy"]),
            int(r["minutes"]), int(r["goalMinutes"]), cs_str(r["goalType"]), cs_str(r["goal"]), int(r["goalGold"])))
    L.append("        };")
    L.append("        public static readonly AdventureRow[] Adventures = {")
    for r in s["adventure"]["rows"]:
        L.append("            new AdventureRow { Id = %s, Name = %s, Description = %s, ProgressKey = %s, StartingCharacter = %s, Characters = new[] { %s }, Stages = new[] { %s }, StartingCoins = %d, CompletionCoins = %d }," % (
            cs_str(r["id"]), cs_str(r["name"]), cs_str(r["description"]), cs_str(r["progressKey"]), cs_str(r["startingCharacter"]),
            ", ".join(cs_str(c) for c in split(r["characters"])), ", ".join(cs_str(c) for c in split(r["stages"])),
            int(r["startingCoins"]), int(r["completionCoins"])))
    L.append("        };")
    L.append("        /// <summary>Texts added to VS's localisation (sheets/texts.json): term, English.</summary>")
    L.append("        public static readonly string[][] Texts = {")
    for r in s["texts"]["rows"]:
        L.append("            new[] { %s, %s }," % (cs_str(r["term"]), cs_str(r["en"])))
    L.append("        };")
    L.append("        /// <summary>Melty test checks (sheets/checks.json), in order.</summary>")
    L.append("        public static readonly string[] Checks = { %s };" % ", ".join(cs_str(r["id"]) for r in s["checks"]["rows"]))
    L += ["    }", "}", ""]
    write(os.path.join(GEN_VS, "Content.g.cs"), "\n".join(L))
    print("generated into " + GEN_SHARED + " and " + GEN_VS)


def write(p, text):
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


if __name__ == "__main__":
    a = sys.argv[1:]
    if not a:
        print(__doc__)
        sys.exit(2)
    if a[0] == "gen":
        gen()
    elif a[0] == "preflight":
        pkg = a[a.index("--package") + 1] if "--package" in a else None
        sys.exit(preflight("--code" in a, pkg))
    else:
        print(__doc__)
        sys.exit(2)
